CREATE OR ALTER PROCEDURE PA_OBTENER_VENTA(
    @Numero_Documento VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_VENTA, ID_USUARIO, ID_SUCURSAL, ID_CLIENTE, TIPO_DOCUMENTO, NUMERO_DOCUMENTO,
           ISNULL(MONTO_PAGO, 0)   AS MONTO_PAGO,
           ISNULL(MONTO_CAMBIO, 0) AS MONTO_CAMBIO,
           ISNULL(MONTO_TOTAL, 0)  AS MONTO_TOTAL,
           ISNULL(DESCUENTO, 0)    AS DESCUENTO,
           CONVERT(CHAR(10), (FECHA_VENTA AT TIME ZONE 'UTC') AT TIME ZONE 'SA Pacific Standard Time', 103) AS FECHA_VENTA
    FROM VENTA
    WHERE NUMERO_DOCUMENTO = @Numero_Documento;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_DETALLES_VENTA(
    @Id_Venta INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_PRODUCTO,
           ISNULL(PRECIO_VENTA, 0) AS PRECIO_VENTA,
           ISNULL(CANTIDAD, 0)     AS CANTIDAD,
           ISNULL(SUBTOTAL, 0)     AS SUBTOTAL,
           ISNULL(DESCUENTO, 0)    AS DESCUENTO
    FROM DETALLE_VENTA
    WHERE ID_VENTA = @Id_Venta;
END;
GO

CREATE OR ALTER PROCEDURE PA_REGISTRAR_VENTA(
    @ID_USUARIO INT,
    @ID_SUCURSAL INT,
    @ID_CLIENTE INT,
    @TIPO_DOCUMENTO VARCHAR(50),
    @NUMERO_DOCUMENTO VARCHAR(50),
    @MONTO_PAGO DECIMAL(10,2),
    @MONTO_CAMBIO DECIMAL(10,2),
    @DESCUENTO DECIMAL(10,2),
    @DETALLE_VENTA dbo.TI_Detalle_Venta READONLY,
    @RESULTADO BIT OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @RESULTADO = 0;

    BEGIN TRY
        BEGIN TRANSACTION;

        DECLARE @MONTO_TOTAL DECIMAL(10,2);

        -- 1. Calcular monto total
        SELECT @MONTO_TOTAL = SUM(SubTotal) FROM @DETALLE_VENTA;

        -- 2. Insertar cabecera (FECHA_VENTA toma SYSUTCDATETIME() por defecto)
        INSERT INTO VENTA (ID_USUARIO, ID_SUCURSAL, ID_CLIENTE, TIPO_DOCUMENTO, NUMERO_DOCUMENTO, MONTO_PAGO, MONTO_CAMBIO, MONTO_TOTAL, DESCUENTO)
        VALUES (@ID_USUARIO, @ID_SUCURSAL, @ID_CLIENTE, @TIPO_DOCUMENTO, @NUMERO_DOCUMENTO, @MONTO_PAGO, @MONTO_CAMBIO, @MONTO_TOTAL, @DESCUENTO);

        DECLARE @ID_VENTA INT = SCOPE_IDENTITY();

        -- 3. Insertar detalle
        INSERT INTO DETALLE_VENTA (ID_VENTA, ID_PRODUCTO, PRECIO_VENTA, CANTIDAD, SUBTOTAL, DESCUENTO)
        SELECT @ID_VENTA, Id_Producto, Precio_Venta, Cantidad, SubTotal, Descuento FROM @DETALLE_VENTA;

        COMMIT TRANSACTION;
        SET @RESULTADO = 1;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        -- Se relanza el error para que la API lo registre (antes se perdía la causa)
        THROW;
    END CATCH
END;
GO
