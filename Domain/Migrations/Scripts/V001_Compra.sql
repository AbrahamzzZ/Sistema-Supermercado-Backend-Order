CREATE OR ALTER PROCEDURE PA_OBTENER_COMPRA(
    @Numero_Documento VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_COMPRA, ID_USUARIO, ID_SUCURSAL, ID_PROVEEDOR, ID_TRANSPORTISTA, TIPO_DOCUMENTO, NUMERO_DOCUMENTO,
           ISNULL(MONTO_TOTAL, 0) AS MONTO_TOTAL,
           CONVERT(CHAR(10), (FECHA_COMPRA AT TIME ZONE 'UTC') AT TIME ZONE 'SA Pacific Standard Time', 103) AS FECHA_COMPRA
    FROM COMPRA
    WHERE NUMERO_DOCUMENTO = @Numero_Documento;
END;
GO

CREATE OR ALTER PROCEDURE PA_OBTENER_DETALLES_COMPRA(
    @Id_Compra INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT ID_PRODUCTO,
           ISNULL(PRECIO_COMPRA, 0) AS PRECIO_COMPRA,
           ISNULL(PRECIO_VENTA, 0)  AS PRECIO_VENTA,
           ISNULL(CANTIDAD, 0)      AS CANTIDAD,
           ISNULL(SUBTOTAL, 0)      AS SUBTOTAL
    FROM DETALLE_COMPRA
    WHERE ID_COMPRA = @Id_Compra;
END;
GO

CREATE OR ALTER PROCEDURE PA_REGISTRAR_COMPRA(
    @ID_USUARIO INT,
    @ID_SUCURSAL INT,
    @ID_PROVEEDOR INT,
    @ID_TRANSPORTISTA INT,
    @TIPO_DOCUMENTO VARCHAR(50),
    @NUMERO_DOCUMENTO VARCHAR(50),
    @DETALLE_COMPRA dbo.TI_Detalle_Compra READONLY,
    @RESULTADO BIT OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET @RESULTADO = 0;

    BEGIN TRY
        BEGIN TRANSACTION;

        DECLARE @MONTO_TOTAL DECIMAL(10,2);

        -- 1. Calcular total
        SELECT @MONTO_TOTAL = SUM(SubTotal) FROM @DETALLE_COMPRA;

        -- 2. Insertar cabecera (FECHA_COMPRA toma SYSUTCDATETIME() por defecto)
        INSERT INTO COMPRA (ID_USUARIO, ID_SUCURSAL, ID_PROVEEDOR, ID_TRANSPORTISTA, TIPO_DOCUMENTO, NUMERO_DOCUMENTO, MONTO_TOTAL)
        VALUES (@ID_USUARIO, @ID_SUCURSAL, @ID_PROVEEDOR, @ID_TRANSPORTISTA, @TIPO_DOCUMENTO, @NUMERO_DOCUMENTO, @MONTO_TOTAL);

        DECLARE @ID_COMPRA INT = SCOPE_IDENTITY();

        -- 3. Insertar detalle
        INSERT INTO DETALLE_COMPRA (ID_COMPRA, ID_PRODUCTO, PRECIO_COMPRA, PRECIO_VENTA, CANTIDAD, SUBTOTAL)
        SELECT @ID_COMPRA, Id_Producto, Precio_Compra, Precio_Venta, Cantidad, SubTotal FROM @DETALLE_COMPRA;

        COMMIT TRANSACTION;
        SET @RESULTADO = 1;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        -- Se relanza el error para que la API lo registre (antes se perdía la causa)
        THROW;
    END CATCH
END;
GO
